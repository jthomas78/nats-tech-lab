// Builds two derived views of the ADR series from each ADR's YAML front matter:
//
//   obsidian/V3-Platform/Architecture/ADR/ADR-INDEX.md   (generated table)
//   demos/01-dictionary/diagrams/adr-cards.html           (one A4 card per ADR)
//
// Then feed the HTML to export-html-pdf.mjs:
//
//   node build-adr-cards.mjs
//   node export-html-pdf.mjs adr-cards.html \
//     "../../../output/pdf/Architecture Decision Records - Cards.pdf"
//
// Only front matter is read; the ADR prose is never parsed. Fields:
//   adr, title, status, date, scope (lab|v3), context, decision, why,
//   related [n,...], optional applies [n,...] / applied_by [n,...].
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const repo = path.resolve(here, '../../..')
const adrDir = path.join(repo, 'obsidian/V3-Platform/Architecture/ADR')
const indexPath = path.join(adrDir, 'ADR-INDEX.md')
const htmlPath = path.join(here, 'adr-cards.html')

const SCOPE = {
  lab: { label: 'Tech Lab · Dictionary POC', color: 'var(--cyan)' },
  v3: { label: 'Proposed Linebooker V3', color: 'var(--purple)' },
}
const STATUS_COLOR = {
  Accepted: 'var(--green)', Proposed: 'var(--amber)',
  Deprecated: 'var(--red)', Superseded: 'var(--red)',
}

function parseFrontMatter(text, file) {
  const m = text.match(/^---\n([\s\S]*?)\n---\n/)
  if (!m) throw new Error(`${file}: no front matter`)
  const out = {}
  for (const line of m[1].split('\n')) {
    const i = line.indexOf(':')
    if (i < 0) continue
    const k = line.slice(0, i).trim()
    let v = line.slice(i + 1).trim()
    if (/^\[.*\]$/.test(v)) v = v.slice(1, -1).split(',').map(s => s.trim()).filter(Boolean).map(Number)
    else if (/^\d+$/.test(v)) v = Number(v)
    out[k] = v
  }
  for (const req of ['adr', 'title', 'status', 'date', 'scope', 'context', 'decision', 'why']) {
    if (out[req] === undefined) throw new Error(`${file}: front matter missing "${req}"`)
  }
  if (!SCOPE[out.scope]) throw new Error(`${file}: unknown scope "${out.scope}"`)
  return out
}

const adrs = fs.readdirSync(adrDir)
  .filter(f => /^ADR-\d{3}-.*\.md$/.test(f))
  .map(f => ({ file: f, ...parseFrontMatter(fs.readFileSync(path.join(adrDir, f), 'utf8'), f) }))
  .sort((a, b) => a.adr - b.adr)

// filename token must agree with front matter
for (const a of adrs) {
  const [, num, scope, ctx] = a.file.match(/^ADR-(\d{3})-([a-z0-9]+)-([a-z0-9-]+?)-/) || []
  if (Number(num) !== a.adr || scope !== a.scope || !a.file.startsWith(`ADR-${num}-${a.scope}-${a.context}-`)) {
    throw new Error(`${a.file}: filename tokens disagree with front matter (adr=${a.adr} scope=${a.scope} context=${a.context})`)
  }
}

const id = n => `ADR-${String(n).padStart(3, '0')}`
const byNum = Object.fromEntries(adrs.map(a => [a.adr, a]))
const esc = s => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

// ---- ADR-INDEX.md -------------------------------------------------------
const rows = adrs.map(a =>
  `| [${id(a.adr)}](${a.file}) | ${a.scope} | ${a.context} | ${a.status} | ${a.date} | ${a.title} |`)
const index = `# ADR Index

Generated by \`demos/01-dictionary/diagrams/build-adr-cards.mjs\` from each ADR's
front matter. Do not edit by hand; re-run the script. Naming and front matter
rules: [README.md](README.md). Card deck PDF:
\`output/pdf/Architecture Decision Records - Cards.pdf\`.

| ADR | Scope | Context | Status | Date | Title |
|---|---|---|---|---|---|
${rows.join('\n')}

Scopes: \`lab\` = tech-lab / Dictionary POC decision (implemented in this repo);
\`v3\` = Proposed Linebooker V3 platform principle (governs lab decisions, not
itself implemented here).
`
fs.writeFileSync(indexPath, index)

// ---- adr-cards.html -----------------------------------------------------
const rel = a => {
  const parts = []
  if (a.applies?.length) parts.push(`applies ${a.applies.map(id).join(', ')}`)
  if (a.applied_by?.length) parts.push(`applied by ${a.applied_by.map(id).join(', ')}`)
  const others = (a.related || []).filter(n => !(a.applies || []).includes(n) && !(a.applied_by || []).includes(n))
  if (others.length) parts.push(`related ${others.map(id).join(', ')}`)
  return parts
}

